function textWidth(font, text, size) {
  try {
    return font.widthOfTextAtSize(String(text || ''), size);
  } catch {
    return String(text || '').length * size * 0.5;
  }
}

function safeDrawText(page, text, opts) {
  try {
    page.drawText(String(text || ''), opts);
  } catch {
    const fallback = String(text || '').replace(/[^\x09\x0a\x0d\x20-\x7e]/g, '?');
    page.drawText(fallback, opts);
  }
}

async function embedExportFonts(pdf) {
  if (unicodeFontBytes) {
    try {
      pdf.registerFontkit(fontkit);
      const embedded = await pdf.embedFont(unicodeFontBytes, { subset: true });
      return { font: embedded, bold: embedded };
    } catch {
      /* fallback */
    }
  }
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  return { font, bold };
}

async function buildAttendancePdf(records, daysInMonth = [], meta = {}) {
  const rows = displayAttendanceRows(records);
  const pdf = await PDFDocument.create();
  const { font, bold } = await embedExportFonts(pdf);

  let logoImage = null;
  if (logoPngBytes) {
    try {
      logoImage = await pdf.embedPng(logoPngBytes);
    } catch (err) {
      console.warn('attendance export PDF logo embed failed:', err.message || err);
    }
  }

  // A4 Landscape
  const pageWidth = 842;
  const pageHeight = 595;
  const margin = 28;
  const innerWidth = pageWidth - margin * 2; // 786 pt

  const ink = rgb(0.09, 0.12, 0.18);
  const muted = rgb(0.38, 0.42, 0.5);
  const band = rgb(0.1, 0.16, 0.28);
  const section = rgb(0.42, 0.47, 0.55);
  const rowStripe = rgb(0.965, 0.975, 0.985);
  const rule = rgb(0.85, 0.88, 0.92);

  // Table columns without Type (fits innerWidth = 786)
  const cols = [
    { key: 'employee_id', label: 'Emp ID', width: 68, align: 'left' },
    { key: 'name', label: 'Employee Name', width: 145, align: 'left' },
    { key: 'department', label: 'Team', width: 95, align: 'left' },
    { key: 'branch', label: 'Branch', width: 90, align: 'left' },
    { key: 'shift', label: 'Shift', width: 70, align: 'left' },
    { key: 'working_days', label: 'Work Days', width: 55, align: 'right' },
    { key: 'present_days', label: 'Present', width: 55, align: 'right' },
    { key: 'late_days', label: 'Late', width: 48, align: 'right' },
    { key: 'absent_days', label: 'Absent', width: 48, align: 'right' },
    { key: 'leave_days', label: 'Leave', width: 48, align: 'right' },
    { key: 'attendance_rate', label: 'Rate %', width: 58, align: 'right' },
  ];

  let page = null;
  let y = 0;
  let pageNo = 0;

  function drawRight(text, atY, size, usedFont, color) {
    const width = textWidth(usedFont, text, size);
    safeDrawText(page, text, {
      x: pageWidth - margin - width,
      y: atY,
      size,
      font: usedFont,
      color,
    });
  }

  function drawWatermark(target) {
    if (!logoImage) return;
    const maxSide = Math.min(pageWidth, pageHeight) * 0.55;
    const scale = Math.min(maxSide / logoImage.width, maxSide / logoImage.height);
    const width = logoImage.width * scale;
    const height = logoImage.height * scale;
    target.drawImage(logoImage, {
      x: (pageWidth - width) / 2,
      y: (pageHeight - height) / 2,
      width,
      height,
      opacity: 0.12,
    });
  }

  function addPage() {
    page = pdf.addPage([pageWidth, pageHeight]);
    pageNo += 1;
    y = pageHeight - margin;

    // Brand header
    safeDrawText(page, 'TEXTURED LAB', {
      x: margin,
      y,
      size: 9,
      font: bold,
      color: section,
    });
    drawRight('Confidential monthly attendance record', y, 8, font, section);
    y -= 13;

    const generatedBy = String(meta.generatedBy || '').trim();
    if (generatedBy) {
      drawRight(`Report generated by ${generatedBy}`, y, 8, font, section);
    }

    // Title
    safeDrawText(page, meta.title || 'Monthly Attendance Report', {
      x: margin,
      y,
      size: 15,
      font: bold,
      color: ink,
    });
    y -= 16;

    // Subtitle
    const monthLabel = meta.month || meta.monthKey || '';
    safeDrawText(
      page,
      `Month: ${monthLabel}  |  ${meta.filters || 'All Employees'}  |  ${rows.length} ${rows.length === 1 ? 'employee' : 'employees'}  |  ${meta.generatedAt || ''}`,
      { x: margin, y, size: 8.5, font, color: muted }
    );
    y -= 10;

    // Divider line
    page.drawLine({
      start: { x: margin, y: y + 3 },
      end: { x: pageWidth - margin, y: y + 3 },
      thickness: 1.2,
      color: band,
    });
    y -= 10;

    // Table Header
    drawTableHeader();
  }

  function drawTableHeader() {
    const headerH = 18;
    page.drawRectangle({
      x: margin,
      y: y - headerH,
      width: innerWidth,
      height: headerH,
      color: band,
    });

    let currentX = margin + 6;
    cols.forEach((col) => {
      let drawX = currentX;
      if (col.align === 'right') {
        const tw = textWidth(bold, col.label, 7.5);
        drawX = currentX + col.width - tw - 4;
      } else if (col.align === 'center') {
        const tw = textWidth(bold, col.label, 7.5);
        drawX = currentX + (col.width - tw) / 2;
      }
      safeDrawText(page, col.label, {
        x: drawX,
        y: y - 12,
        size: 7.5,
        font: bold,
        color: rgb(0.97, 0.98, 0.99),
      });
      currentX += col.width;
    });

    y -= (headerH + 2);
  }

  addPage();

  if (!rows.length) {
    safeDrawText(page, 'No employees matched the selected filters.', {
      x: margin,
      y: y - 20,
      size: 10,
      font,
      color: muted,
    });
    return Buffer.from(await pdf.save());
  }

  const rowHeight = 17;
  for (let rIdx = 0; rIdx < rows.length; rIdx += 1) {
    const row = rows[rIdx];

    // Check if new page needed
    if (y - rowHeight < margin + 25) {
      addPage();
    }

    // Alternating zebra stripe
    if (rIdx % 2 === 1) {
      page.drawRectangle({
        x: margin,
        y: y - rowHeight,
        width: innerWidth,
        height: rowHeight,
        color: rowStripe,
      });
    }

    // Bottom row border line
    page.drawLine({
      start: { x: margin, y: y - rowHeight },
      end: { x: pageWidth - margin, y: y - rowHeight },
      thickness: 0.4,
      color: rule,
    });

    let currentX = margin + 6;
    cols.forEach((col) => {
      let val = String(row[col.key] ?? '—');
      const maxW = col.width - 6;
      while (textWidth(font, val, 7.5) > maxW && val.length > 3) {
        val = val.slice(0, -2) + '…';
      }

      let drawX = currentX;
      if (col.align === 'right') {
        const tw = textWidth(font, val, 7.5);
        drawX = currentX + col.width - tw - 4;
      } else if (col.align === 'center') {
        const tw = textWidth(font, val, 7.5);
        drawX = currentX + (col.width - tw) / 2;
      }

      const isRate = col.key === 'attendance_rate';
      safeDrawText(page, val, {
        x: drawX,
        y: y - 11.5,
        size: 7.5,
        font: isRate || col.key === 'employee_id' ? bold : font,
        color: ink,
      });

      currentX += col.width;
    });

    y -= rowHeight;
  }

  // Footer and watermark on all pages
  const allPages = pdf.getPages();
  allPages.forEach((p, idx) => {
    drawWatermark(p);
    safeDrawText(p, `Page ${idx + 1} of ${allPages.length}`, {
      x: pageWidth / 2 - 25,
      y: 12,
      size: 7.5,
      font,
      color: muted,
    });
    safeDrawText(p, 'Confidential · Textured Lab HR & Attendance Management', {
      x: margin,
      y: 12,
      size: 7,
      font,
      color: muted,
    });
  });

  return Buffer.from(await pdf.save());
}

