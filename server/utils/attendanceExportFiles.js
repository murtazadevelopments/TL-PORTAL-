function xmlEscape(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function filenamePart(value, fallback) {
  const cleaned = String(value || '')
    .replace(/[<>:"/\\|?*\u0000-\u001f]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return cleaned || fallback;
}

function buildAttendanceBaseName(filters = {}, monthKey = '') {
  const month = filenamePart(monthKey || 'Month', 'Month');
  const team = filters.team
    ? filenamePart(filters.team, 'All Teams')
    : 'All Teams';
  const branch = filters.branch
    ? filenamePart(filters.branch, 'All Branches')
    : 'All Branches';
  const shift = filters.shift
    ? filenamePart(filters.shift, 'All Shifts')
    : '';

  return ['TL Attendance', month, team, branch, shift]
    .filter(Boolean)
    .join(' ')
    .trim();
}

function excelSheetPasswordHash(password) {
  const text = String(password || '');
  let verifier = 0;
  for (let i = text.length - 1; i >= 0; i -= 1) {
    verifier = ((verifier >> 14) & 0x01) | ((verifier << 1) & 0x7fff);
    verifier ^= text.charCodeAt(i) & 0xff;
  }
  verifier = ((verifier >> 14) & 0x01) | ((verifier << 1) & 0x7fff);
  verifier ^= text.length;
  verifier ^= 0xce4b;
  return verifier.toString(16).toUpperCase().padStart(4, '0');
}

function displayAttendanceRows(records) {
  return (records || []).map((row) => ({
    id: row.id,
    employee_id: row.employee_id || '—',
    name: row.name || '—',
    department: row.department || '—',
    branch: row.branch || '—',
    shift: row.shift || '—',
    total_days: Number(row.total_days ?? 0),
    working_days: Number(row.working_days ?? 0),
    present_days: Number(row.present_days ?? 0),
    late_days: Number(row.late_days ?? 0),
    absent_days: Number(row.absent_days ?? 0),
    leave_days: Number(row.leave_days ?? 0),
    holiday_days: Number(row.holiday_days ?? 0),
    attendance_rate: `${Number(row.attendance_rate ?? 0)}%`,
    daily_codes: row.daily_codes || {},
  }));
}

